import { test,expect } from '@playwright/test'
import type { Page } from '@playwright/test'
async function connect(page:Page){await page.goto('/');await page.getByLabel('Development owner credential').fill(process.env.ZPERMIT_BROWSER_OWNER!);await page.getByLabel('Development agent credential').fill(process.env.ZPERMIT_BROWSER_AGENT!);await page.getByRole('button',{name:'Connect workspace'}).click();await expect(page.getByText('Available to agents')).toBeVisible()}
const owner=()=>({'Authorization':`Bearer ${process.env.ZPERMIT_BROWSER_OWNER}`})
const agent=()=>({'Authorization':`Bearer ${process.env.ZPERMIT_BROWSER_AGENT}`})
test('real UI and policy API: create, reserve, deny, approve, revoke, responsive layout',async({page,request})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await connect(page)
 await page.getByRole('button',{name:'Create permit',exact:true}).click()
 const dialog=page.getByRole('dialog')
 await dialog.getByLabel('Permit name').fill('Browser review permit')
 await dialog.getByLabel('Total budget · USD').fill('10.00')
 await dialog.getByLabel('Maximum per purchase · USD').fill('1.00')
 await dialog.getByLabel('Approval threshold · USD').fill('0.50')
 await dialog.getByLabel('Expiration · local time').fill('2030-01-01T12:00')
 await dialog.getByLabel('Allowed merchant identifiers').fill('swiggy-money-india')
 await dialog.getByLabel('Allowed category identifiers').fill('gift_card')
 await dialog.getByRole('button',{name:'Create permit',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Browser review permit'})).toBeVisible()
 const permits=await (await request.get('/api/permits',{headers:owner()})).json()
 const permit=permits.find((p:{name:string})=>p.name==='Browser review permit')
 const proposal={permit_id:permit.id,agent_id:permit.agent_id,merchant:'swiggy-money-india',category:'gift_card',product_id:'swiggy-money-india',amount_cents:55,currency:'USD',external_request_id:crypto.randomUUID()}
 const p=await (await request.post('/api/purchase-requests',{headers:agent(),data:proposal})).json()
 expect(p.state).toBe('pending_approval')
 const denial=await (await request.post('/api/purchase-requests',{headers:agent(),data:{...proposal,amount_cents:1001,external_request_id:crypto.randomUUID()}})).json()
 expect(denial.state).toBe('denied');expect(denial.denial_reason).toBe('per_purchase_limit_exceeded')
 await page.getByRole('button',{name:'Agent requests',exact:true}).click()
 await page.getByRole('button',{name:'Refresh workspace'}).click()
 await page.getByRole('button',{name:`View request ${p.id}`,exact:true}).click()
 await page.getByRole('button',{name:'Approve reservation'}).click()
 await page.getByRole('dialog').getByRole('button',{name:'Confirm',exact:true}).click()
 await expect(page.getByText('authorized',{exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:'Live purchase blocked'})).toBeDisabled()
 const snapshot=await (await request.get('/api/workspace',{headers:owner()})).json()
 expect(snapshot.permits[0].spending.active_reservations_cents).toBe(55)
 await page.getByRole('button',{name:'Overview',exact:true}).click()
 await page.screenshot({path:'/tmp/zpermit-dashboard.png',fullPage:true})
 for(const width of [390,768]){await page.setViewportSize({width,height:900});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)}
 await page.screenshot({path:'/tmp/zpermit-mobile.png',fullPage:true})
 await page.setViewportSize({width:1440,height:1000})
 await page.getByRole('button',{name:'Spending permits',exact:true}).click()
 await page.getByRole('button').filter({hasText:'Browser review permit'}).first().click()
 await page.getByRole('button',{name:'Revoke permit',exact:true}).click()
 await page.getByRole('dialog').getByRole('button',{name:'Confirm',exact:true}).click()
 await expect(page.getByText('revoked',{exact:true})).toBeVisible()
 const after=await (await request.get(`/api/permits/${permit.id}`,{headers:owner()})).json()
 expect(after.spending.active_reservations_cents).toBe(0)
 expect(errors).toEqual([])
})
